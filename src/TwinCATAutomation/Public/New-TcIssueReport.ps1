function New-TcIssueReport {
    <#
    .SYNOPSIS
        Builds a de-identified, pre-filled GitHub "new issue" URL (and the same title / body as text) for a problem found while using this module; it creates nothing and calls no server.
    .DESCRIPTION
        #78. Read-only and offline: no GitHub API call, no token, no network access, no IDE / ADS call
        (so it also works while the IDE is blocked by a modal dialog, and it is not refused by
        LIFECYCLE_BLOCKED). It only formats text. The user opens data.url in a browser, reviews the
        body and presses "Submit new issue" with their own GitHub account; the agent must never open
        or submit it for them, and must show data.maskReport and data.body to the user first (the
        repository is PUBLIC, anybody can read the issue).

        The body has the sections Call (tool + parameters), Result (the failing result JSON),
        Expected, Notes, Environment and a footer that lists the masks that were applied. The
        environment only uses what the module already knows in memory: module version, git commit
        of the module checkout (read from the .git files, no git process), PowerShell and OS version,
        whether an IDE / ADS connection exists, the IDE ProgId and the TwinCAT.Ads.dll version that was
        loaded. The solution file name is left out unless -IncludeSolutionName is given. Nothing is
        read from the IDE or the target; the TwinCAT / XAE version is therefore not included unless
        you write it in -Notes.

        De-identification (applied to every input, object keys included, before the URL is built;
        data.masks says how many of each): Windows user names in paths (C:\Users\<user>\), this
        machine's computer / user / domain names, URLs (host and path; github.com,
        infosys.beckhoff.com and learn.microsoft.com stay), host names with a company / TLD suffix
        (*.local, *.corp, *.com ...), values under Address / HostName / RouteName keys, UNC server
        names, AMS NetIds (<netid>; loopback 127.x.x.x.y.z stays), IPv4 / IPv6 addresses and MAC
        addresses (a dotted number right after the WORD version stays), e-mail addresses, drive /
        forward-slash / file:/// / relative paths: a solution / project file keeps only its file name
        (<path>\Main.sln), every other path outside C:\TwinCAT, C:\Windows, C:\Program Files and
        ProgramData\Beckhoff keeps only a leaf with a log / txt / json ... extension; when a path
        cannot be told apart from the prose behind it the whole rest of the line is masked. In a
        TIPC^ tree path every segment after TIPC is masked. The base name of the open solution is
        masked everywhere. Values under keys such as password / token / secret, "password=..."
        style text (quoted values and "password is x" too), well-known token shapes (GitHub, sk-,
        AWS, JWT, Bearer) and long letter+digit runs (keys) are masked. A token that is split
        across two lines is NOT recognised. The masks are heuristics: a customer or site name
        inside a sentence is only masked when you list it in -ExtraMask. error.hint of the Result
        is dropped (it is generated by the module, long, and non-ASCII text makes the URL 9 times
        longer).

        URL length: browsers and servers cut long URLs, and GitHub does not document a limit
        (the default 7000 is a conservative value that was NOT measured). The encoded URL is limited
        to -MaxUrlLength characters: the largest of Result / Parameters / Notes / Expected is shortened
        first and ends with "[truncated]" (data.truncated, data.truncatedSections). Inputs are masked
        first (inside a wide raw cap of 30000 characters, 20000 per JSON string, 150000 in total, at most 3000
        tree nodes) and the MASKED text is cut afterwards at a word boundary (10000 characters per
        section, 3000 per JSON string), never inside a placeholder and never in the middle of a token
        that was masked, so no prefix of a secret is left behind. data.body is therefore complete only
        with respect to that bounded input; it can be pasted into the issue form by hand when the
        URL version was shortened. The title is limited to 120 characters.

        Source: the "issues/new?title=&body=&labels=" query parameters pre-fill a new issue (GitHub Docs
        https://docs.github.com/en/issues/tracking-your-work-with-issues/using-issues/creating-an-issue
        and https://docs.github.com/en/issues/tracking-your-work-with-issues/using-issues/about-automation-for-issues-and-pull-requests-with-query-parameters).
        What GitHub does with a label that does not exist in the repository is not stated there: it
        is expected to be ignored for users without triage permission (not verified).
    .PARAMETER Title
        One-line summary of the problem (becomes the issue title, 120 characters at most).
    .PARAMETER Tool
        Name of the MCP tool or cmdlet that was called, e.g. 'BuildProject' or 'Enable-TcConfig'.
    .PARAMETER Parameters
        The parameters of that call: an object, or a JSON string. Credential-like keys are masked.
    .PARAMETER Result
        The failing result: the {success, error, data} object returned by the tool, or its JSON string.
        error.hint is dropped.
    .PARAMETER Expected
        What you expected to happen instead.
    .PARAMETER Notes
        Anything else: steps before the call, TwinCAT / XAE version and target kind (UmRT, CX ...), what was tried.
    .PARAMETER Label
        Issue label in the URL. Default 'field-report'. Empty = no labels parameter.
    .PARAMETER MaxUrlLength
        Upper limit of the encoded URL in characters, 2000..8000. Default 7000.
    .PARAMETER ExtraMask
        Literal strings (customer, site, plant, person names) to replace with <redacted> everywhere.
    .PARAMETER NoEnvironment
        Leave the Environment section out.
    .PARAMETER IncludeSolutionName
        Put the solution file name of the connected IDE into the Environment section (left out by default).
    .OUTPUTS
        data: url, urlLength, maxUrlLength, truncated, truncatedSections, title, body, bodyLength,
        masks (name -> count), maskReport, environment, repository, labels, howToSubmit.
    .EXAMPLE
        New-TcIssueReport -Title 'BuildProject returns BUILD_TIMEOUT on a small project' -Tool BuildProject -Result $buildResult
    .EXAMPLE
        New-TcIssueReport -Title 'EnableConfig stops at Activate' -Tool EnableConfig -Parameters @{ Force = $true } -Expected 'PLC reaches Run' -ExtraMask 'ACME'
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Title,

        [Parameter()]
        [string]$Tool,

        [Parameter()]
        [object]$Parameters,

        [Parameter()]
        [object]$Result,

        [Parameter()]
        [string]$Expected,

        [Parameter()]
        [string]$Notes,

        [Parameter()]
        [string]$Label = 'field-report',

        [Parameter()]
        [ValidateRange(2000, 8000)]
        [int]$MaxUrlLength = 7000,

        [Parameter()]
        [string[]]$ExtraMask,

        [Parameter()]
        [switch]$NoEnvironment,

        [Parameter()]
        [switch]$IncludeSolutionName
    )

    if ([string]::IsNullOrWhiteSpace($Title)) {
        return New-TcResult -Success $false -ErrorCode 'INVALID_PARAMS' -ErrorMessage '-Title is empty: give a one-line summary of the problem.'
    }

    $baseUrl = 'https://github.com/Lance0901/AI-TwinCAT-Skill/issues/new'
    $inputCap = 10000      # characters per input AFTER masking (cut at a word boundary)
    $rawCap = 30000        # wide raw cap before masking (bounds the work, the partial token at the cut is dropped)
    $jsonParseCap = 100000 # a longer JSON string is kept as (cut) text instead of being parsed
    $counts = @{}

    # --- helpers
    # Mask FIRST (inside a wide raw cap, the partial token at that cut is dropped), cut the MASKED text
    # at a word boundary afterwards: a cut before masking would leave prefixes of tokens that no rule recognises.
    function ConvertTo-BoundedText {
        param([string]$Text, [int]$Cap, [string]$Marker = '')
        $raw = Limit-TcRawText -Text $Text -Cap $rawCap
        $m = ConvertTo-TcDeidentifiedText -Text $raw -Counts $counts -ExtraMask $maskList
        if ($m.Length -gt $Cap) { $m = (Limit-TcMaskedText -Text $m -Cap $Cap) + $Marker }
        return $m
    }
    function Limit-MaskedJson {
        param([string]$Text, [int]$Cap)
        if ($Text.Length -le $Cap) { return $Text }
        return (Limit-TcMaskedText -Text $Text -Cap $Cap) + "`n[input cut at $Cap characters]"
    }
    function ConvertTo-IssueTree {
        param($Value)
        if ($null -eq $Value) { return $null }
        if ($Value -is [string]) {
            $t = $Value.Trim()
            if ($t.Length -gt 0 -and $t.Length -le $jsonParseCap -and ($t.StartsWith('{') -or $t.StartsWith('['))) {
                try { return (ConvertFrom-Json -InputObject $t) } catch { return $Value }
            }
            return $Value
        }
        return $Value
    }
    function Get-IssueProp {
        param($Obj, [string]$Name)
        if ($null -eq $Obj) { return $null }
        if ($Obj -is [System.Collections.IDictionary]) { if ($Obj.Contains($Name)) { return $Obj[$Name] } else { return $null } }
        $p = $Obj.PSObject.Properties[$Name]
        if ($null -ne $p) { return $p.Value }
        return $null
    }
    function ConvertTo-IssueJson {
        param($Tree)
        if ($Tree -is [string]) { return $Tree }
        $j = ConvertTo-Json -InputObject $Tree -Depth 12 -Compress
        # PS 5.1 escapes these ASCII characters; keep the placeholders (<user>) readable
        return ($j -replace '\\u0027', "'" -replace '\\u003c', '<' -replace '\\u003e', '>' -replace '\\u0026', '&')
    }
    # Length of Uri.EscapeDataString(Text) without calling it (that call throws above ~65519 characters on .NET Framework).
    function Get-EncodedLength {
        param([string]$Text)
        $n = 0
        $i = 0
        $len = $Text.Length
        while ($i -lt $len) {
            $ch = $Text[$i]
            $code = [int]$ch
            if (($code -ge 48 -and $code -le 57) -or ($code -ge 65 -and $code -le 90) -or ($code -ge 97 -and $code -le 122) -or $ch -eq '-' -or $ch -eq '_' -or $ch -eq '.' -or $ch -eq '~' -or $ch -eq '!' -or $ch -eq '*' -or $ch -eq "'" -or $ch -eq '(' -or $ch -eq ')') { $n += 1 }
            elseif ($code -lt 128) { $n += 3 }
            elseif ($code -lt 2048) { $n += 6 }
            elseif ([char]::IsHighSurrogate($ch) -and ($i + 1) -lt $len -and [char]::IsLowSurrogate($Text[$i + 1])) { $n += 12; $i++ }
            else { $n += 9 }
            $i++
        }
        return $n
    }

    # --- names that must never appear: the open solution, PLC names seen in TIPC^ paths of the inputs
    $mask = [System.Collections.Generic.List[string]]::new()
    foreach ($m in @($ExtraMask)) { if (-not [string]::IsNullOrWhiteSpace($m)) { $mask.Add($m) } }
    foreach ($n in @(Get-TcIssueKnownNames)) { if ($n -and -not $mask.Contains($n)) { $mask.Add($n) } }
    # the probe holds every input as text (objects as JSON), so TIPC^ names in objects are found too
    $probeParts = [System.Collections.Generic.List[string]]::new()
    foreach ($x in @($Title, $Tool, $Expected, $Notes)) { if ($x) { $probeParts.Add([string]$x) } }
    foreach ($x in @($Parameters, $Result)) {
        if ($null -eq $x) { continue }
        if ($x -is [string]) { $probeParts.Add($x) }
        else { try { $probeParts.Add((ConvertTo-Json -InputObject $x -Depth 12 -Compress)) } catch { $null = $_ } }
    }
    $rawProbe = Limit-TcRawText -Text ($probeParts -join "`n") -Cap 100000
    foreach ($m in [regex]::Matches($rawProbe, 'TIPC\^([^\^\r\n"''`;,|]{2,80})')) {
        $n = $m.Groups[1].Value.Trim()
        if ($n.Length -ge 2 -and $n -notmatch '^(?i:untitled\d*)$' -and -not $mask.Contains($n)) { $mask.Add($n) }
    }
    # dry run over all inputs: the folder names of every path become mask words for ALL inputs
    $probeCounts = @{}
    $null = ConvertTo-TcDeidentifiedText -Text $rawProbe -Counts $probeCounts -ExtraMask $mask.ToArray()
    if ($probeCounts.ContainsKey('__folders')) {
        foreach ($f in $probeCounts['__folders']) { if (-not $mask.Contains($f)) { $mask.Add($f) } }
    }
    $maskList = $mask.ToArray()

    # --- title / tool
    $titleText = ConvertTo-BoundedText -Text (($Title -replace '\s+', ' ').Trim()) -Cap 400
    if ($titleText.Length -gt 120) {
        $titleText = (Limit-TcMaskedText -Text $titleText -Cap 117) + '...'
    }
    $toolText = ''
    if (-not [string]::IsNullOrWhiteSpace($Tool)) {
        $toolText = ConvertTo-BoundedText -Text (($Tool -replace '\s+', ' ').Trim()) -Cap 200
    }

    # --- parameters / result
    $state = @{ Nodes = 0; Cut = 0; Chars = 0 }
    $paramsText = ''
    if ($null -ne $Parameters -and -not ($Parameters -is [string] -and [string]::IsNullOrWhiteSpace($Parameters))) {
        $tree = ConvertTo-IssueTree $Parameters
        if ($tree -is [string]) { $paramsText = ConvertTo-BoundedText -Text $tree -Cap $inputCap -Marker "`n[input cut at $inputCap characters]" }
        else {
            $masked = ConvertTo-TcDeidentifiedValue -Value $tree -Counts $counts -ExtraMask $maskList -State $state
            $paramsText = Limit-MaskedJson -Text (ConvertTo-IssueJson $masked) -Cap $inputCap
        }
    }

    $resultText = ''
    $errorCode = ''
    $resultSuccess = $null
    if ($null -ne $Result -and -not ($Result -is [string] -and [string]::IsNullOrWhiteSpace($Result))) {
        $tree = ConvertTo-IssueTree $Result
        if ($tree -is [string]) { $resultText = ConvertTo-BoundedText -Text $tree -Cap $inputCap -Marker "`n[input cut at $inputCap characters]" }
        else {
            $err = Get-IssueProp $tree 'error'
            $codeValue = Get-IssueProp $err 'code'
            if ($null -ne $codeValue) {
                $cv = [string]$codeValue
                if ($cv -match '^[A-Z0-9_]{1,64}$') { $errorCode = $cv }
                else { $errorCode = ConvertTo-BoundedText -Text ($cv -replace '[\r\n`]+', ' ') -Cap 80 }
            }
            $sv = Get-IssueProp $tree 'success'
            if ($sv -is [bool]) { $resultSuccess = $sv }
            $state = @{ Nodes = 0; Cut = 0; Chars = 0 }
            $masked = ConvertTo-TcDeidentifiedValue -Value $tree -Counts $counts -ExtraMask $maskList -OmitKey @('hint') -State $state
            $resultText = Limit-MaskedJson -Text (ConvertTo-IssueJson $masked) -Cap $inputCap
        }
    }

    $marker10k = "`n[input cut at $inputCap characters]"
    $expectedText = ''
    if (-not [string]::IsNullOrWhiteSpace($Expected)) { $expectedText = ConvertTo-BoundedText -Text $Expected.Trim() -Cap $inputCap -Marker $marker10k }
    $notesText = ''
    if (-not [string]::IsNullOrWhiteSpace($Notes)) { $notesText = ConvertTo-BoundedText -Text $Notes.Trim() -Cap $inputCap -Marker $marker10k }

    # --- environment: only what the module already holds in memory
    $environment = $null
    $envLines = @()
    if (-not $NoEnvironment) {
        $environment = Get-TcIssueEnvironment -IncludeSolutionName:$IncludeSolutionName
        $envMasked = [ordered]@{}
        foreach ($k in $environment.Keys) {
            $v = $environment[$k]
            # version-like values (adsDllVersion 4.4.0.0) look like IP addresses: only free-form values are masked
            if ($v -is [string] -and @('ideProgId', 'ideSelectedBy') -contains $k) { $v = ConvertTo-TcDeidentifiedText -Text $v -Counts $counts -ExtraMask $maskList }
            $envMasked[$k] = $v
        }
        $environment = $envMasked
        foreach ($k in $environment.Keys) { $envLines += ('- {0}: {1}' -f $k, $environment[$k]) }
    }

    # --- body: sections are rendered from (possibly shortened) texts
    $marker = '[truncated]'
    $texts = [ordered]@{ Result = $resultText; Parameters = $paramsText; Notes = $notesText; Expected = $expectedText }
    $truncated = [System.Collections.Generic.List[string]]::new()

    $render = {
        param($T)
        $parts = [System.Collections.Generic.List[string]]::new()
        if ($toolText -ne '' -or $T.Parameters -ne '') {
            $sb = '## Call'
            if ($toolText -ne '') { $sb += "`n" + 'Tool: `' + $toolText + '`' }
            if ($T.Parameters -ne '') { $sb += "`n`n" + '```json' + "`n" + $T.Parameters + "`n" + '```' }
            $parts.Add($sb)
        }
        if ($T.Result -ne '') {
            $sb = '## Result'
            if ($errorCode -ne '') { $sb += "`n" + 'error.code: `' + $errorCode + '`' }
            elseif ($null -ne $resultSuccess) { $sb += "`n" + 'success: `' + [string]$resultSuccess + '`' }
            $sb += "`n`n" + '```json' + "`n" + $T.Result + "`n" + '```'
            $parts.Add($sb)
        }
        if ($T.Expected -ne '') { $parts.Add("## Expected`n" + $T.Expected) }
        if ($T.Notes -ne '') { $parts.Add("## Notes`n" + $T.Notes) }
        if ($envLines.Count -gt 0) { $parts.Add("## Environment`n" + ($envLines -join "`n")) }
        return , $parts
    }

    $maskFooter = {
        $names = @($counts.Keys | Where-Object { $_ -notlike '__*' } | Sort-Object)
        if ($names.Count -eq 0) { return '_De-identified automatically by New-TcIssueReport (no masks were needed). Review before submitting._' }
        $list = ($names | ForEach-Object { '{0} x{1}' -f $_, $counts[$_] }) -join ', '
        return ('_De-identified automatically by New-TcIssueReport; masks applied: ' + $list + '. Review before submitting._')
    }

    $buildBody = {
        $parts = & $render $texts
        $parts.Add((& $maskFooter))
        return ($parts -join "`n`n")
    }
    $fullBodyText = [string](& $buildBody)

    # --- label (masked and reduced to harmless characters)
    $labelClean = ''
    if (-not [string]::IsNullOrWhiteSpace($Label)) {
        $labelClean = (ConvertTo-BoundedText -Text $Label.Trim() -Cap 50) -replace '[^A-Za-z0-9 _.:-]', ''
        $labelClean = $labelClean.Trim()
    }
    $labelPart = ''
    if ($labelClean -ne '') { $labelPart = '&labels=' + [System.Uri]::EscapeDataString($labelClean) }
    $titlePart = '?title=' + [System.Uri]::EscapeDataString($titleText)

    # --- shorten the largest section until the encoded URL fits (lengths are computed, never by escaping the whole body)
    $bodyForUrl = $fullBodyText
    $guard = 0
    while ($true) {
        $urlLen = $baseUrl.Length + $titlePart.Length + 6 + (Get-EncodedLength $bodyForUrl) + $labelPart.Length
        if ($urlLen -le $MaxUrlLength -or $guard -gt 300) { break }
        $guard++
        $victim = $null
        $victimLen = 0
        foreach ($k in $texts.Keys) {
            $t = [string]$texts[$k]
            if ($t -eq '' -or $t -eq $marker) { continue }
            $l = Get-EncodedLength $t
            if ($l -gt $victimLen) { $victim = $k; $victimLen = $l }
        }
        if ($null -eq $victim) { break }
        $t = [string]$texts[$victim]
        $body = $t
        if ($body.EndsWith($marker)) { $body = $body.Substring(0, $body.Length - $marker.Length).TrimEnd() }
        $excess = $urlLen - $MaxUrlLength
        # cut by the excess (encoded characters are 1..9 characters each: cut generously, at least a quarter)
        $cut = [Math]::Max([int]($body.Length * 0.25), [int]($excess / 3) + 1)
        $newLen = [Math]::Max(0, $body.Length - $cut)
        $texts[$victim] = ((Limit-TcMaskedText -Text $body -Cap $newLen) + "`n" + $marker).Trim()
        if (-not $truncated.Contains($victim)) { $truncated.Add($victim) }
        $bodyForUrl = [string](& $buildBody)
    }

    # the body is bounded by the input caps (well below the ~65519 characters Uri.EscapeDataString accepts)
    $url = $baseUrl + $titlePart + '&body=' + [System.Uri]::EscapeDataString($bodyForUrl) + $labelPart
    $urlTooLong = $url.Length -gt $MaxUrlLength

    $countKeys = @($counts.Keys | Where-Object { $_ -notlike '__*' } | Sort-Object)
    $maskReport = if ($countKeys.Count -eq 0) { 'No mask was needed. The text may still contain names this tool cannot recognise: read data.body before submitting.' }
    else { 'Masked: ' + (($countKeys | ForEach-Object { '{0} x{1}' -f $_, $counts[$_] }) -join ', ') + '. Customer / site / person names inside sentences are NOT detected unless listed in -ExtraMask: read data.body before submitting.' }

    $maskTable = [ordered]@{}
    foreach ($k in $countKeys) { $maskTable[$k] = $counts[$k] }

    $howTo = 'Show data.maskReport and data.body to the user. Only the user opens data.url in a browser signed in to GitHub, checks the text and presses Submit new issue; do not open or submit it yourself. '
    if ($truncated.Count -gt 0) { $howTo += 'The URL version was shortened (' + ($truncated -join ', ') + '): paste data.body into the form instead of using the URL if the whole text is needed.' }

    $labelList = @()
    if ($labelClean -ne '') { $labelList = @($labelClean) }
    $data = [ordered]@{
        url               = $url
        urlLength         = $url.Length
        maxUrlLength      = $MaxUrlLength
        truncated         = ($truncated.Count -gt 0)
        truncatedSections = @($truncated)
        title             = $titleText
        body              = $fullBodyText
        bodyLength        = $fullBodyText.Length
        masks             = $maskTable
        maskReport        = $maskReport
        environment       = $environment
        repository        = 'Lance0901/AI-TwinCAT-Skill'
        labels            = @($labelList)
        howToSubmit       = $howTo.Trim()
    }
    if ($urlTooLong) {
        $data['warning'] = 'The URL is longer than -MaxUrlLength even with every section shortened (title or environment too long). Paste data.body into the new issue form by hand.'
    }
    return (New-TcResult -Success $true -Data ([PSCustomObject]$data))
}
